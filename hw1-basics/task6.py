"""
Задание 6 со звёздочкой (продвинутый трек). Шифр Виженера.

В расшифрованном отчёте (task1) упомянут ещё один слой - короткое сообщение,
зашифрованное уже не Цезарем, а шифром Виженера: у каждой буквы свой сдвиг,
который задаётся соответствующей буквой ключа.
"""


def decode_vigenere_cipher(text: str, key: str) -> str:
    """
    Расшифровать text, зашифрованный шифром Виженера с ключом key.

    В отличие от шифра Цезаря, здесь у каждой буквы свой сдвиг: i-я по счёту
    ЛАТИНСКАЯ БУКВА исходного текста была сдвинута вперёд по алфавиту на
    величину, которая определяется i-й буквой ключа key (a/A -> сдвиг 0,
    b/B -> сдвиг 1, ..., z/Z -> сдвиг 25). Ключ короче текста и применяется
    циклически: после того как ключ закончился, снова берём его с начала.
    Регистр key значения не имеет - важна только буква.

    Ловушка: позиция по ключу продвигается только на латинских буквах текста.
    Цифры, пробелы и знаки препинания не сдвигаются и НЕ расходуют символ
    ключа - они просто пропускаются, а ключ на них не сдвигается вперёд.
    Регистр букв исходного текста должен сохраняться.

    Пример: decode_vigenere_cipher("Rijvs, Uyvjn!", "key") -> "Hello, World!"
    """
    shifts = [ord(ch) - ord("a") for ch in key.lower() if "a" <= ch <= "z"]
    result = []
    key_pos = 0
    for ch in text:
        if "a" <= ch <= "z":
            base = ord("a")
        elif "A" <= ch <= "Z":
            base = ord("A")
        else:
            result.append(ch)
            continue
        shift = shifts[key_pos % len(shifts)]
        result.append(chr((ord(ch) - base - shift) % 26 + base))
        key_pos += 1
    return "".join(result)


